#!/usr/bin/env node
import { mkdir, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '../..');
const { version } = JSON.parse(await readFile(resolve(REPO_ROOT, 'server/package.json'), 'utf8'));
const output = resolve(REPO_ROOT, 'server/dist-local/appforge-mcp.mjs');

await mkdir(dirname(output), { recursive: true });
await build({
  entryPoints: [resolve(REPO_ROOT, 'server/src/local/server.ts')],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  minify: false,
  charset: 'utf8',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: `#!/usr/bin/env node\n// AppForge local MCP server v${version} — generated by server/scripts/build-local.mjs`,
  },
});

console.error(`✓ wrote ${output}`);
console.error(`  AppForge local MCP server v${version}`);
