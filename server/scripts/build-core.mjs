#!/usr/bin/env node
import { mkdir, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '../..');
const releaseSource = await readFile(resolve(REPO_ROOT, 'server/src/lib/release.ts'), 'utf8');
const ANALYZER_CORE_VERSION = releaseSource
  .match(/export const WORKER_VERSION\s*=\s*['"]([^'"]+)['"]/u)?.[1];
if (!ANALYZER_CORE_VERSION) throw new Error('unable to read WORKER_VERSION from src/lib/release.ts');
const output = resolve(REPO_ROOT, 'cli/dist/analyzer-core.mjs');

await mkdir(dirname(output), { recursive: true });
await build({
  entryPoints: [resolve(REPO_ROOT, 'server/src/cli-artifact.ts')],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  charset: 'utf8',
  sourcemap: false,
  legalComments: 'none',
  define: {
    __ANALYZER_CORE_VERSION__: JSON.stringify(ANALYZER_CORE_VERSION),
  },
  banner: {
    js: `// AppForge analyzer core v${ANALYZER_CORE_VERSION} — generated by server/scripts/build-core.mjs`,
  },
});

console.error(`✓ wrote ${output}`);
console.error(`  AppForge analyzer core v${ANALYZER_CORE_VERSION}`);
