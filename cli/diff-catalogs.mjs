#!/usr/bin/env node
/** Compare two extracted YAML catalog snapshots without reading retired tables.
 * Usage: node cli/diff-catalogs.mjs <baseline-directory> <candidate-directory>
 * Writes cli/diff-report.md. This diagnostic does not approve catalog changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseManifest, parseProperties } from '../server/scripts/lib/catalog-source.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPORT_PATH = join(REPO_ROOT, 'cli/diff-report.md');
const [baselineDirectory, candidateDirectory, ...extra] = process.argv.slice(2);
if (!baselineDirectory || !candidateDirectory || extra.length) {
  throw new Error('Usage: node cli/diff-catalogs.mjs <baseline-directory> <candidate-directory>');
}
function load(directory) {
  const manifest = parseManifest(readFileSync(join(resolve(directory), 'control-manifest.yml'), 'utf8'));
  const properties = parseProperties(readFileSync(join(resolve(directory), 'control-properties.yml'), 'utf8'));
  if (!manifest.controls.length || !Object.keys(properties.controls).length) {
    throw new Error(`Empty catalog snapshot: ${directory}`);
  }
  return { controls: new Map(manifest.controls.map(control => [control.type, control])),
    properties: properties.controls };
}
const baseline = load(baselineDirectory);
const candidate = load(candidateDirectory);
const difference = (left, right) => [...left].filter(value => !right.has(value)).sort();
const propertyNames = entry => new Set([
  ...Object.keys(entry?.input_properties ?? {}),
  ...Object.values(entry?.variant_input_properties ?? {}).flatMap(Object.keys),
]);
const names = snapshot => new Set([...snapshot.controls.keys(), ...Object.keys(snapshot.properties)]);
const before = names(baseline), after = names(candidate);
const shared = [...before].filter(name => after.has(name)).sort();
const lines = ['# Catalog snapshot diff', '', 'Generated by `cli/diff-catalogs.mjs`.', '',
  'Review aid only; catalog acceptance still requires the verification doctrine and release gate.', '',
  '## Controls', '', '| Snapshot | Controls |', '|---|---:|',
  `| Baseline | ${before.size} |`, `| Candidate | ${after.size} |`, '',
  `Removed: ${difference(before, after).join(', ') || '(none)'}`,
  `Added: ${difference(after, before).join(', ') || '(none)'}`, '', '## Shared controls', ''];
let changed = 0;
for (const name of shared) {
  const oldInputs = propertyNames(baseline.properties[name]);
  const newInputs = propertyNames(candidate.properties[name]);
  const oldOutputs = new Set(baseline.properties[name]?.output_properties ?? []);
  const newOutputs = new Set(candidate.properties[name]?.output_properties ?? []);
  const oldVariants = new Set(baseline.controls.get(name)?.variants ?? []);
  const newVariants = new Set(candidate.controls.get(name)?.variants ?? []);
  const changes = [
    ['Removed inputs', difference(oldInputs, newInputs)],
    ['Added inputs', difference(newInputs, oldInputs)],
    ['Removed outputs', difference(oldOutputs, newOutputs)],
    ['Added outputs', difference(newOutputs, oldOutputs)],
    ['Removed variants', difference(oldVariants, newVariants)],
    ['Added variants', difference(newVariants, oldVariants)],
  ].filter(([, values]) => values.length);
  if (!changes.length) continue;
  changed++;
  lines.push(`### ${name}`, '', ...changes.map(([label, values]) => `- ${label}: ${values.join(', ')}`), '');
}
if (!changed) lines.push('No input, output or variant changes.', '');
writeFileSync(REPORT_PATH, lines.join('\n'));
console.log(`Wrote ${REPORT_PATH}: ${before.size} baseline controls, ${after.size} candidate controls, ${changed} shared controls changed.`);
